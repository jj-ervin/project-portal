import {test, expect} from '@playwright/test';
import axe from 'axe-core';

test('tasks can be associated, edited, completed, reopened, exported and imported', async ({page}) => {
  await page.goto('/');
  await page.getByRole('button',{name:'New project'}).first().click();
  await page.getByRole('dialog',{name:'Create project'}).getByLabel('Project name').fill('Research');
  await page.getByRole('button',{name:'Create project',exact:true}).click();
  await page.getByRole('group',{name:'Project sections'}).getByRole('button',{name:'Tasks'}).click();
  await page.getByLabel('New milestone').fill('Review');
  await page.getByRole('button',{name:'Add milestone'}).click();
  await page.getByLabel('New deliverable').fill('Report');
  await page.getByRole('button',{name:'Add deliverable'}).click();
  await page.locator('#entry-form').getByLabel('Task title').fill('Write draft');
  await page.locator('#entry-form').getByLabel('Milestone').selectOption({label:'Review'});
  await page.locator('#entry-form').getByLabel('Deliverable').selectOption({label:'Report'});
  await page.locator('#entry-form').getByLabel('Open work in').selectOption('url');
  await page.locator('#entry-form').getByLabel('URL or absolute Windows path').fill('https://example.com/draft');
  await page.getByRole('button',{name:'Add task'}).click();
  await expect(page.locator('.task-summary')).toContainText('0/1 tasks complete');
  await expect(page.locator('.task-summary')).toContainText('Next action: Write draft');
  await expect(page.locator('.task-row')).toContainText('Milestone: Review');
  await expect(page.getByRole('button',{name:'Open next action'})).toBeVisible();
  const popup=page.waitForEvent('popup');
  await page.getByRole('button',{name:'Open next action'}).click();
  await expect(await popup).toHaveURL('https://example.com/draft');
  await page.getByRole('button',{name:'Edit',exact:true}).click();
  await page.locator('#task-edit-form').getByLabel('Task title').fill('Write first draft');
  await page.getByRole('button',{name:'Save task'}).click();
  await page.getByRole('button',{name:'Complete',exact:true}).click();
  await expect(page.locator('.task-summary')).toContainText('1/1 tasks complete');
  await page.reload();
  await page.getByRole('button',{name:'Open Research'}).click();
  await page.getByRole('group',{name:'Project sections'}).getByRole('button',{name:'Tasks'}).click();
  await expect(page.locator('.task-row')).toContainText('Write first draft');
  const download = page.waitForEvent('download');
  await page.locator('summary[aria-label="More project actions"]').click();
  await page.getByRole('button',{name:'Export JSON'}).click();
  const path = await (await download).path();
  await page.locator('#import').setInputFiles(path);
  await page.getByRole('button',{name:'Replace projects'}).click();
  await page.getByRole('button',{name:'Open Research'}).click();
  await page.getByRole('group',{name:'Project sections'}).getByRole('button',{name:'Tasks'}).click();
  await page.getByRole('button',{name:'Reopen'}).click();
  await expect(page.locator('.task-summary')).toContainText('Next action: Write first draft');
  const saved=await page.evaluate(()=>JSON.parse(localStorage.getItem('propro-project-portal-v1')));
  expect(saved.projects[0].items[0]).toMatchObject({title:'Write first draft',completed:false,milestoneId:saved.projects[0].milestones[0].id,deliverableId:saved.projects[0].deliverables[0].id,connection:{kind:'url',locator:'https://example.com/draft'}});
});

test('legacy tasks remain editable with keyboard and fit narrow screens', async ({page}) => {
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await page.evaluate(()=>localStorage.setItem('propro-project-portal-v1',JSON.stringify({version:1,projects:[{id:'legacy',name:'Existing research',capabilities:[],items:[{id:'old',title:'Original task'}],resources:[],evidence:[],links:[]}]})));
  await page.reload();
  await page.getByRole('button',{name:'Open Existing research'}).click();
  await page.getByRole('group',{name:'Project sections'}).getByRole('button',{name:'Tasks'}).click();
  await page.getByRole('button',{name:'Complete',exact:true}).press('Enter');
  await expect(page.locator('.task-summary')).toContainText('1/1 tasks complete');
  await page.addScriptTag({content:axe.source});
  const violations=await page.evaluate(async()=> (await axe.run(document,{runOnly:{type:'tag',values:['wcag2a','wcag2aa','wcag21aa','wcag22aa']}})).violations);
  expect(violations).toEqual([]);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
  await page.screenshot({path:'docs/screenshots/propro-tasks-390.png',fullPage:true});
  await page.setViewportSize({width:1280,height:800});
  await page.screenshot({path:'docs/screenshots/propro-tasks-1280.png',fullPage:true});
});
